package com.itheima.docker;

/**
 * Docker 自定义镜像学习笔记
 *
 * 主题：Docker 镜像结构详解
 */
public class CustomImage {
    /*
     * ====================================================================
     *                        Dockerfile 简介
     * ====================================================================
     *
     * Dockerfile 就是一个文本文件，其中包含一个个的指令（Instruction），
     * 用指令来说明要执行什么操作来构建镜像。
     * 将来 Docker 可以根据 Dockerfile 帮我们构建镜像。
     *
     *
     * ====================================================================
     *                        Dockerfile 常见指令
     * ====================================================================
     *
     * ┌─────────────┬────────────────────────────────────────┬──────────────────────────────────┐
     * │    指令     │                 说明                   │              示例                │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ FROM        │ 指定基础镜像                           │ FROM centos:7                    │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ ENV         │ 设置环境变量，可在后面指令使用         │ ENV key=value                    │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ COPY        │ 拷贝本地文件到镜像的指定目录           │ COPY ./jdk17.tar.gz /tmp         │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ RUN         │ 执行Linux的shell命令，一般是安装过程   │ RUN tar -zxvf /tmp/jdk17.tar.gz  │
     * │             │ 的命令                                 │                                  │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ EXPOSE      │ 指定容器运行时监听的端口，是给镜像使   │ EXPOSE 8080                      │
     * │             │ 用者看的                               │                                  │
     * ├─────────────┼────────────────────────────────────────┼──────────────────────────────────┤
     * │ ENTRYPOINT  │ 镜像中应用的启动命令，容器运行时调用   │ ENTRYPOINT java -jar xx.jar      │
     * └─────────────┴────────────────────────────────────────┴──────────────────────────────────┘
     *
     *
     * ====================================================================
     *                        Docker 镜像结构（分层架构）
     * ====================================================================
     *
     * Docker 镜像采用分层结构设计，由下至上依次为：
     *
     *
     * 1️⃣ 基础镜像（BaseImage）
     * ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
     * 【位置】最底层，是镜像的基础
     * 【内容】包含应用依赖的系统函数库、环境变量、基础配置、文件系统等
     * 【示例】
     *    - openjdk:11-jre        // Java 运行环境
     *    - ubuntu:20.04          // Ubuntu 操作系统
     *    - nginx:alpine          // 轻量级 Nginx
     *    - python:3.9-slim       // Python 运行环境
     * 【作用】提供程序运行所需的底层环境支持
     *
     *
     * 2️⃣ 层（Layer）
     * ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
     * 【位置】中间层，可以有多层
     * 【内容】添加安装包、依赖库、配置文件、应用程序等
     * 【特点】
     *    ✓ 每次操作（如 RUN、COPY、ADD）都会形成新的一层
     *    ✓ 层与层之间是增量关系，不会修改下层内容
     *    ✓ 每一层都是只读的（Read-Only）
     *    ✓ 相同的层可以被多个镜像共享，节省存储空间
     * 【示例操作】
     *    - RUN apt-get install xxx    // 安装软件包，形成新层
     *    - COPY app.jar /app/         // 复制应用文件，形成新层
     *    - RUN mkdir /data            // 创建目录，形成新层
     * 【分层优势】
     *    ✓ 复用性：多个镜像可共享相同的基础层
     *    ✓ 高效性：修改时只需重新构建变化的层
     *    ✓ 可追溯：每一层的变更都有记录
     *
     *
     * 3️⃣ 入口（Entrypoint）
     * ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
     * 【位置】最顶层，是镜像的执行入口
     * 【内容】定义镜像运行时启动的脚本和参数
     * 【作用】容器启动时自动执行的命令
     * 【Dockerfile 配置】
     *    - ENTRYPOINT ["java", "-jar", "/app/app.jar"]  // 固定启动命令
     *    - CMD ["--spring.profiles.active=prod"]        // 默认参数（可被覆盖）
     * 【示例】
     *    当容器启动时，会执行：
     *    java -jar /app/app.jar --spring.profiles.active=prod
     *
     *
     * ====================================================================
     *                        镜像分层的实际意义
     * ====================================================================
     *
     * 🔹 存储优化
     *    - 相同的基础镜像层只存储一份
     *    - 例如：10个基于 openjdk:11 的镜像，只需存储一份 openjdk:11 层
     *
     * 🔹 构建加速
     *    - 修改代码重新构建时，只需重新构建变化的层
     *    - 未变化的层直接使用缓存
     *
     * 🔹 分发高效
     *    - 推送镜像时，只推送不存在的层
     *    - 拉取镜像时，只下载缺失的层
     *
     * 🔹 版本管理
     *    - 每一层都有唯一的 ID（SHA256 哈希）
     *    - 可以精确追踪镜像的构建历史
     *
     *
     * ====================================================================
     *                        查看镜像分层命令
     * ====================================================================
     *
     * docker image inspect <镜像名>      // 查看镜像详细信息
     * docker history <镜像名>            // 查看镜像构建历史（每一层的命令）
     *
     *
     * ====================================================================
     *                        最佳实践
     * ====================================================================
     *
     * ✅ 合并 RUN 命令减少层数
     *    不推荐：
     *      RUN apt-get update
     *      RUN apt-get install -y curl
     *      RUN apt-get clean
     *    推荐：
     *      RUN apt-get update && \
     *          apt-get install -y curl && \
     *          apt-get clean
     *
     * ✅ 将变化频繁的层放在上层
     *    - 基础环境放底层（变化少）
     *    - 应用代码放上层（变化多）
     *
     * ✅ 使用 .dockerignore 减少上下文
     *    避免将不必要的文件打包进镜像
     *
     * ✅ 选择合适的基础镜像
     *    - alpine 系列：体积小，适合生产环境
     *    - slim 系列：精简版，去除不必要的工具
     */
}
